-- ============================================================================
-- ASA Kenya - Migration 002: Graduate Architects Hub
--   graduate_interest     - the graduate interest / mentorship form
--   alert_subscriptions   - opt-in opportunity alerts (separate from everything else)
--   portfolio_submissions - optional portfolio showcase, moderated before publication
-- Run AFTER migration 001 (it uses public.is_admin()).
-- These tables are completely separate from the existing student registration,
-- membership and contact processes (those use Formspree and are not touched).
-- Safe to re-run.
-- ============================================================================
begin;

-- ---------------------------------------------------------------------------
-- 1. GRADUATE INTEREST FORM
--    The public can INSERT only. Nobody can read these rows except administrators.
-- ---------------------------------------------------------------------------
create table if not exists public.graduate_interest (
  id              uuid primary key default gen_random_uuid(),
  interest_type   text not null default 'graduate' check (interest_type in ('graduate', 'mentee', 'mentor')),
  full_name       text not null check (char_length(btrim(full_name)) between 2 and 120),
  email           text not null check (char_length(email) <= 254 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  university      text check (university is null or char_length(btrim(university)) between 2 and 160),   -- mentors: practice / organisation
  graduation_year integer check (graduation_year is null or graduation_year between 1960 and 2100),
  location        text check (location is null or char_length(location) <= 120),
  skills          text check (skills is null or char_length(skills) <= 500),
  interests       text[] not null default '{}' check (cardinality(interests) <= 20),
  portfolio_url   text check (portfolio_url is null or (portfolio_url ~* '^https://[^[:space:]]+$' and char_length(portfolio_url) <= 2000)),
  consent         boolean not null check (consent is true),
  privacy_version text not null default 'v1',
  created_at      timestamptz not null default now(),
  -- graduates and mentees must say where and when they studied; mentors need not
  constraint graduate_interest_study_ck check (
    interest_type = 'mentor' or (university is not null and graduation_year is not null))
);

alter table public.graduate_interest enable row level security;
revoke all on public.graduate_interest from anon, authenticated;
-- Column-level INSERT: the browser cannot choose id, created_at or privacy_version.
grant insert (interest_type, full_name, email, university, graduation_year, location,
              skills, interests, portfolio_url, consent)
  on public.graduate_interest to anon, authenticated;
grant select, delete on public.graduate_interest to authenticated;

drop policy if exists gi_public_insert on public.graduate_interest;
drop policy if exists gi_admin_read    on public.graduate_interest;
drop policy if exists gi_admin_delete  on public.graduate_interest;

create policy gi_public_insert on public.graduate_interest
  for insert to anon, authenticated with check (consent is true);
create policy gi_admin_read on public.graduate_interest
  for select to authenticated using ((select public.is_admin()));
create policy gi_admin_delete on public.graduate_interest
  for delete to authenticated using ((select public.is_admin()));

-- ---------------------------------------------------------------------------
-- 2. OPPORTUNITY ALERT SUBSCRIPTIONS (opt-in, confirm, unsubscribe)
--    The browser can only create a PENDING subscription (email + categories + consent).
--    confirm_token / unsubscribe_token are generated by the database and are never
--    readable from the website. An email service (not part of this migration) must
--    send the confirmation and unsubscribe links. Until that exists, nobody is
--    emailed and subscriptions stay unconfirmed. See SETUP-SUPABASE.md.
-- ---------------------------------------------------------------------------
create table if not exists public.alert_subscriptions (
  id                uuid primary key default gen_random_uuid(),
  email             text not null check (char_length(email) <= 254 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  categories        text[] not null check (cardinality(categories) between 1 and 20),
  consent           boolean not null check (consent is true),
  confirm_token     uuid not null default gen_random_uuid(),
  unsubscribe_token uuid not null default gen_random_uuid(),
  confirmed_at      timestamptz,
  unsubscribed_at   timestamptz,
  created_at        timestamptz not null default now()
);
create unique index if not exists alert_subscriptions_email_uq on public.alert_subscriptions (lower(email));

alter table public.alert_subscriptions enable row level security;
revoke all on public.alert_subscriptions from anon, authenticated;
grant insert (email, categories, consent) on public.alert_subscriptions to anon, authenticated;
-- Administrators can see who subscribed, but never the tokens.
grant select (id, email, categories, consent, confirmed_at, unsubscribed_at, created_at)
  on public.alert_subscriptions to authenticated;
grant delete on public.alert_subscriptions to authenticated;

drop policy if exists as_public_insert on public.alert_subscriptions;
drop policy if exists as_admin_read    on public.alert_subscriptions;
drop policy if exists as_admin_delete  on public.alert_subscriptions;

create policy as_public_insert on public.alert_subscriptions
  for insert to anon, authenticated with check (consent is true);
create policy as_admin_read on public.alert_subscriptions
  for select to authenticated using ((select public.is_admin()));
create policy as_admin_delete on public.alert_subscriptions
  for delete to authenticated using ((select public.is_admin()));

-- Confirm / unsubscribe by token (the token arrives in an emailed link).
create or replace function public.confirm_alert_subscription(p_token uuid)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare n integer;
begin
  update public.alert_subscriptions
     set confirmed_at = coalesce(confirmed_at, now()), unsubscribed_at = null
   where confirm_token = p_token;
  get diagnostics n = row_count;
  return n > 0;
end;
$$;

create or replace function public.unsubscribe_alert(p_token uuid)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare n integer;
begin
  update public.alert_subscriptions
     set unsubscribed_at = coalesce(unsubscribed_at, now())
   where unsubscribe_token = p_token;
  get diagnostics n = row_count;
  return n > 0;
end;
$$;

revoke all on function public.confirm_alert_subscription(uuid) from public;
revoke all on function public.unsubscribe_alert(uuid)          from public;
grant execute on function public.confirm_alert_subscription(uuid) to anon, authenticated;
grant execute on function public.unsubscribe_alert(uuid)          to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. PORTFOLIO SHOWCASE (optional, consent-based, moderated)
--    Submissions start as 'pending'. Only approved ones are public, and only the
--    public-facing columns (never the email).
-- ---------------------------------------------------------------------------
create table if not exists public.portfolio_submissions (
  id              uuid primary key default gen_random_uuid(),
  full_name       text not null check (char_length(btrim(full_name)) between 2 and 120),
  email           text not null check (char_length(email) <= 254 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  university      text not null check (char_length(btrim(university)) between 2 and 160),
  graduation_year integer not null check (graduation_year between 1960 and 2100),
  headline        text not null check (char_length(btrim(headline)) between 3 and 160),
  bio             text check (bio is null or char_length(bio) <= 1500),
  portfolio_url   text not null check (portfolio_url ~* '^https://[^[:space:]]+$' and char_length(portfolio_url) <= 2000),
  consent_publish boolean not null check (consent_publish is true),
  status          text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_by     uuid references auth.users (id) on delete set null,
  reviewed_at     timestamptz,
  created_at      timestamptz not null default now()
);
create index if not exists portfolio_status_idx on public.portfolio_submissions (status);

create or replace function public.portfolio_guard()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  end if;
  return new;
end;
$$;
drop trigger if exists portfolio_guard_trg on public.portfolio_submissions;
create trigger portfolio_guard_trg
  before update on public.portfolio_submissions
  for each row execute function public.portfolio_guard();

alter table public.portfolio_submissions enable row level security;
revoke all on public.portfolio_submissions from anon, authenticated;
-- Public insert: the status is not in this list, so it is always 'pending'.
grant insert (full_name, email, university, graduation_year, headline, bio, portfolio_url, consent_publish)
  on public.portfolio_submissions to anon, authenticated;
-- Public read: approved rows, public columns only (no email).
grant select (id, full_name, university, graduation_year, headline, bio, portfolio_url, created_at, status)
  on public.portfolio_submissions to anon;
grant select, delete on public.portfolio_submissions to authenticated;
grant update (status) on public.portfolio_submissions to authenticated;

drop policy if exists ps_public_insert on public.portfolio_submissions;
drop policy if exists ps_public_read   on public.portfolio_submissions;
drop policy if exists ps_admin_read    on public.portfolio_submissions;
drop policy if exists ps_admin_update  on public.portfolio_submissions;
drop policy if exists ps_admin_delete  on public.portfolio_submissions;

create policy ps_public_insert on public.portfolio_submissions
  for insert to anon, authenticated with check (consent_publish is true);
-- Anonymous visitors only: logged-in users read through the admin policy below, so a
-- non-admin account can never see email addresses.
create policy ps_public_read on public.portfolio_submissions
  for select to anon using (status = 'approved');
create policy ps_admin_read on public.portfolio_submissions
  for select to authenticated using ((select public.is_admin()));
create policy ps_admin_update on public.portfolio_submissions
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy ps_admin_delete on public.portfolio_submissions
  for delete to authenticated using ((select public.is_admin()));

commit;
